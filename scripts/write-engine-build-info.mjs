import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const digest = value => createHash("sha256").update(value).digest("hex");
async function filesIn(relative) {
  const result = [];
  for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
    const file = `${relative}/${entry.name}`;
    if (entry.isDirectory()) result.push(...await filesIn(file));
    else if (entry.isFile()) result.push(file);
  }
  return result.sort();
}
const files = [];
for (const directory of ["engine/include", "engine/src"]) {
  for (const file of await filesIn(directory)) files.push({ path: file, sha256: digest(await readFile(path.join(root, file))) });
}
const wasmPath = "apps/web/public/physics/voxel_physics.wasm";
const wasm = await readFile(path.join(root, wasmPath));
const { instance } = await WebAssembly.instantiate(wasm, {});
if (instance.exports.physics_abi_version() !== 4 || instance.exports.voxel_stride() !== 5) {
  throw new Error("The current engine requires a new adapter for this ABI.");
}
const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
const info = {
  schemaVersion: 1,
  sourceRepository: git("remote", "get-url", "origin"),
  sourceTree: digest(JSON.stringify(files)),
  sourceDirectory: "engine",
  abiVersion: 4,
  voxelStride: 5,
  wasm: { path: wasmPath, sha256: digest(wasm), bytes: wasm.length },
  files,
};
await writeFile(path.join(root, "engine/current/build-info.json"), `${JSON.stringify(info, null, 2)}\n`);
const exports = {
  ENGINE_SOURCE_REPOSITORY: info.sourceRepository,
  ENGINE_SOURCE_COMMIT: null,
  ENGINE_SOURCE_TREE: info.sourceTree,
  ENGINE_WASM_SHA256: info.wasm.sha256,
};
await writeFile(path.join(root, "engine/current/build-info.mjs"),
  "// Generated by scripts/write-engine-build-info.mjs; sourceTree hashes the actual C++ files.\n" +
  Object.entries(exports).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};`).join("\n") + "\n");
console.log(`Canonical engine: ABI 4, ${wasm.length} bytes, SHA-256 ${info.wasm.sha256}`);

// Register the completed binary and adapters only after build metadata is durable.
const { CurrentVersions } = await import("../benchmarking/current-version.mjs");
new CurrentVersions(root).read();
