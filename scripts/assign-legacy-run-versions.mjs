import { readFile, writeFile, mkdir, rename, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { assignLegacyVersions, assignedLegacyMetadata } from '../benchmarking/legacy-version-assignment.mjs';

const [catalogueFile = 'outputs/version-audit/catalogue.json', matchesFile = 'outputs/version-audit/legacy-matches.json'] = process.argv.slice(2);
const catalogue = JSON.parse(await readFile(catalogueFile));
const matches = JSON.parse(await readFile(matchesFile));
const snapshots = catalogue.versions.filter(v => v.generation === '1.0').map(v => ({ ...v, version: v.research_snapshot || v.version }));
const assigned = assignLegacyVersions(catalogue.legacy_runs, snapshots, matches.runs);
const folder = path.dirname(path.resolve(catalogueFile));
await mkdir(folder, { recursive: true });
const repository = catalogue.sources.find(s => s.type === 'legacy-repository')?.path;
if (repository) {
  // Preserve the actual fetched GitHub-ref log used for this reconstruction.
  const log = execFileSync('git', ['-C', repository, 'log', '--remotes=origin', '--format=%H%x09%cI%x09%s', '--since=2026-07-01', '--until=2026-09-05'], { encoding: 'utf8', maxBuffer: 16*1024*1024 });
  await writeFile(path.join(folder, 'legacy-github-history.tsv'), log);
  assigned.git_history = { repository: 'https://github.com/mazebench/MazeBenchEngine', log: 'legacy-github-history.tsv',
    remote_main: execFileSync('git', ['-C', repository, 'rev-parse', 'origin/main'], { encoding: 'utf8' }).trim() };
  const remoteCommits = new Set(execFileSync('git', ['-C', repository, 'log', '--remotes=origin', '--format=%H'], { encoding: 'utf8' }).trim().split('\n'));
  assigned.git_history.local_only_commits = [];
  for (const row of assigned.runs) {
    const a = row.assignment;
    a.source = remoteCommits.has(a.commit) ? 'github' : 'local-git';
    if (a.source === 'local-git') {
      a.github_url = null;
      a.notes.push('This source commit survives in local Git history only.');
      if (!assigned.git_history.local_only_commits.includes(a.commit)) assigned.git_history.local_only_commits.push(a.commit);
    }
  }
}
await writeFile(path.join(folder, 'legacy-assignments.json'), JSON.stringify(assigned, null, 2) + '\n');
// Version identities are source-controlled; original run artifacts are not.
await writeFile(new URL('../benchmarking/legacy-version-registry.mjs', import.meta.url),
  '// Generated by scripts/assign-legacy-run-versions.mjs. Chronological legacy engine releases; no run records.\nexport const legacyVersions = ' +
  JSON.stringify(assigned.releases.map(({version,engine,first_run_at})=>({version,engine,first_run_at})), null, 2) + ';\n');
const importsFile = new URL('../benchmarking/imports/index.json', import.meta.url);
const imports = JSON.parse(await readFile(importsFile));
await copyFile(importsFile, path.join(folder, 'imports-before-chronological-versions.json'), 1).catch(e=>{if(e.code!=='EEXIST')throw e;});
const byId = new Map(assigned.runs.map(r => [r.id,r]));
for (const run of imports.runs) {
  const row = byId.get(run.source?.run_id);
  if (row) run.benchmark_version = assignedLegacyMetadata(row, run.benchmark_version);
}
const temporary = new URL('../benchmarking/imports/index.json.version-tmp', import.meta.url);
await writeFile(temporary, JSON.stringify(imports) + '\n'); await rename(temporary, importsFile);
console.log(JSON.stringify({ assigned_runs: assigned.runs.length, engine_versions: assigned.releases.length,
  first: assigned.runs[0]?.assigned_version, last: `v${assigned.releases.at(-1)?.version}`,
  methods: Object.fromEntries([...new Set(assigned.runs.map(r=>r.assignment.method))].map(method=>[method,assigned.runs.filter(r=>r.assignment.method===method).length])) },null,2));
